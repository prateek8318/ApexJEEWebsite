export const defaultChapterId = "ch-04";

export const getChapterById = (chapterId: string) => {
  for (const subject of selfLearningSubjects) {
    for (const unit of subject.units) {
      const chapter = unit.chapters.find((item) => item.id === chapterId);
      if (chapter) {
        return { subject, unit, chapter };
      }
    }
  }
  return null;
};
